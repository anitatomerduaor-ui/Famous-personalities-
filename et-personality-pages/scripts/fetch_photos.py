#!/usr/bin/env python3
"""Download real, freely licensed portrait photos for the personality pages.

For each person it asks Wikipedia for the article's lead image, checks that the
file lives on Wikimedia Commons (free licence), downloads a 1200px version to
assets/photos/<slug>.jpg and writes credits to assets/photo-credits.js, which
the pages read to show the photographer and licence.

Needs network access to en.wikipedia.org, commons.wikimedia.org and
upload.wikimedia.org. Standard library only.

    python3 scripts/fetch_photos.py

For production, replace these with ET's licensed agency photos (PTI, Reuters,
Getty) and keep the same file names.
"""
import json
import pathlib
import re
import sys
import urllib.parse
import urllib.request

PEOPLE = {
    "jensen-huang": "Jensen_Huang",
    "mukesh-ambani": "Mukesh_Ambani",
    "raghuram-rajan": "Raghuram_Rajan",
    "donald-trump": "Donald_Trump",
}

ROOT = pathlib.Path(__file__).resolve().parent.parent
PHOTOS = ROOT / "assets" / "photos"
CREDITS_JS = ROOT / "assets" / "photo-credits.js"
UA = {"User-Agent": "et-personalities-prototype/0.2 (internal prototype)"}


def get_json(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def strip_html(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", s or "")).strip()


def fetch(slug, title):
    summary = get_json("https://en.wikipedia.org/api/rest_v1/page/summary/" + title)
    src = (summary.get("originalimage") or {}).get("source")
    if not src:
        raise RuntimeError("article has no lead image")
    filename = urllib.parse.unquote(src.rsplit("/", 1)[-1])

    q = urllib.parse.urlencode({
        "action": "query", "format": "json", "prop": "imageinfo",
        "titles": "File:" + filename,
        "iiprop": "url|extmetadata", "iiurlwidth": "1200",
    })
    data = get_json("https://commons.wikimedia.org/w/api.php?" + q)
    page = next(iter(data["query"]["pages"].values()))
    if "imageinfo" not in page:
        raise RuntimeError(filename + " is not on Wikimedia Commons (may be non-free); skipped")
    info = page["imageinfo"][0]
    meta = info.get("extmetadata", {})
    img_url = info.get("thumburl") or info["url"]

    req = urllib.request.Request(img_url, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        (PHOTOS / (slug + ".jpg")).write_bytes(r.read())

    return {
        "artist": strip_html(meta.get("Artist", {}).get("value")) or "Unknown",
        "license": strip_html(meta.get("LicenseShortName", {}).get("value")) or "See source",
        "source": info.get("descriptionurl", ""),
        "file": filename,
    }


def main():
    PHOTOS.mkdir(parents=True, exist_ok=True)
    credits, failed = {}, []
    for slug, title in PEOPLE.items():
        try:
            credits[slug] = fetch(slug, title)
            c = credits[slug]
            print(f"ok    {slug}: {c['file']} · {c['artist']} · {c['license']}")
        except Exception as e:  # keep going for the others
            failed.append(slug)
            print(f"FAIL  {slug}: {e}", file=sys.stderr)
    CREDITS_JS.write_text(
        "/* Generated by scripts/fetch_photos.py. Do not edit by hand. */\n"
        "window.PHOTO_CREDITS = " + json.dumps(credits, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"\n{len(credits)} downloaded, {len(failed)} failed. Credits: {CREDITS_JS.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
